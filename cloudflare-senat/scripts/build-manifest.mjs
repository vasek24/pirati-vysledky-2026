// Generates src/manifest.js (candidate registry + Pirate-backed list) from the ČSÚ open data.
// Usage: node scripts/build-manifest.mjs <serk.json> <cpp.json> <cns.json> <navig_obvody.json>
// Deterministic: same inputs -> same output. Exits non-zero on any unresolved/ambiguous owner entry.
import { readFileSync, writeFileSync } from 'node:fs'
import { createHash } from 'node:crypto'
import { fileURLToPath } from 'node:url'

const OUT = fileURLToPath(new URL('../src/manifest.js', import.meta.url))
const PIRATE_NSTRANA = 720

// Owner list: relation, obvod, surname, expected ballot number
const OWNER = [
  ['ticket', 30, 'Šípová', 2], ['ticket', 18, 'Luftová', 5], ['ticket', 75, 'Szyja', 2],
  ['endorsed', 21, 'Šarapatka', 2], ['endorsed', 24, 'Smoljak', 2], ['endorsed', 27, 'Padevět', 7],
  ['endorsed', 3, 'Plevný', 1], ['endorsed', 6, 'Hluštíková', 4], ['endorsed', 33, 'Štross', 5],
  ['endorsed', 45, 'Dvořák', 7], ['endorsed', 48, 'Grulich', 2], ['endorsed', 51, 'Černý', 4],
  ['endorsed', 54, 'Třetina', 2], ['endorsed', 57, 'Grolich', 2], ['endorsed', 60, 'Papoušek', 1],
  ['endorsed', 66, 'Kohajda', 1], ['endorsed', 69, 'Pešatová', 6], ['endorsed', 72, 'Šimetka', 3],
]

const [serkPath, cppPath, cnsPath, navigPath] = process.argv.slice(2)
if (!navigPath) {
  console.error('usage: node scripts/build-manifest.mjs <serk.json> <cpp.json> <cns.json> <navig_obvody.json>')
  process.exit(2)
}
const fail = (msg) => { console.error(`FAIL: ${msg}`); process.exit(1) }
const read = (p) => readFileSync(p)
const sha = (buf) => createHash('sha256').update(buf).digest('hex')
const bufs = [serkPath, cppPath, cnsPath, navigPath].map(read)
const [serk, cpp, cns, navig] = bufs.map((b) => JSON.parse(b.toString('utf8')))

const rows = serk.polozky
const pName = new Map(cpp['položky'].map((x) => [x.PSTRANA, x.NAZEV_STRP]))
const nName = new Map(cns['položky'].map((x) => [x.NSTRANA, x.NAZEV_STRN]))
const known = new Set(navig.obvody.map((o) => o.obvod))
const nz = (v) => (v === undefined || v === null || v === '' ? null : v)

const candidates = rows
  .map((r) => ({
    obvod: r.OBVOD,
    no: r.CKAND,
    v: {
      first: r.JMENO, last: r.PRIJMENI, pre: nz(r.TITULPRED), post: nz(r.TITULZA),
      age: nz(r.VEK), job: nz(r.POVOLANI), residence: nz(r.BYDLISTEN),
      party: nName.get(r.NSTRANA) ?? null, partyCode: nz(r.NSTRANA),
      member: pName.get(r.PSTRANA) ?? null, ballotLabel: nz(r.NAZEV_VS),
    },
    nstrana: r.NSTRANA,
  }))
  .sort((a, b) => a.obvod - b.obvod || a.no - b.no)

for (const c of candidates) if (!known.has(c.obvod)) fail(`registry obvod ${c.obvod} is not in navig_obvody.json`)

console.log('obvod  surname      relation  no  registry name                  NSTRANA  nominating party')
const backed = OWNER.map(([relation, obvod, surname, expectedNo]) => {
  const hits = candidates.filter((c) => c.obvod === obvod && c.v.last.toLowerCase().includes(surname.toLowerCase()))
  if (hits.length !== 1) fail(`${obvod}:${surname} matched ${hits.length} registry rows`)
  const [h] = hits
  if (h.no !== expectedNo) fail(`${obvod}:${surname} resolved to no ${h.no}, expected ${expectedNo}`)
  if (relation === 'ticket' && h.nstrana !== PIRATE_NSTRANA) fail(`ticket ${obvod}:${surname} has NSTRANA ${h.nstrana}, not ${PIRATE_NSTRANA}`)
  console.log(`${String(obvod).padEnd(6)} ${surname.padEnd(12)} ${relation.padEnd(9)} ${String(h.no).padEnd(3)} ${`${h.v.first} ${h.v.last}`.padEnd(30)} ${String(h.nstrana).padEnd(8)} ${h.v.party}`)
  return { obvod, no: h.no, relation }
})
const stray = candidates.filter((c) => c.nstrana === PIRATE_NSTRANA && !backed.some((b) => b.obvod === c.obvod && b.no === c.no))
if (stray.length) console.log(`NOTE: registry candidates with NSTRANA ${PIRATE_NSTRANA} not on the owner list: ${stray.map((c) => `${c.obvod}:${c.no}`).join(', ')}`)

const entries = candidates.map((c) => `  '${c.obvod}:${c.no}': ${JSON.stringify(c.v)},`)
const list = backed.map((b) => `  ${JSON.stringify(b)},`)
const header = [
  '// GENERATED by scripts/build-manifest.mjs - do not edit by hand.',
  '// Sources (ČSÚ open data, https://volby.gov.cz/opendata/se2026/):',
  `//   SE2026reg20261007_json.zip -> serk.json            sha256 ${sha(bufs[0])}`,
  `//   SE2026ciselniky20260915_json.zip -> cpp.json       sha256 ${sha(bufs[1])}`,
  `//   SE2026ciselniky20260915_json.zip -> cns.json       sha256 ${sha(bufs[2])}`,
  `//   navig/obvody.json (generovano ${navig.generovano}) sha256 ${sha(bufs[3])}`,
  '// Pirate-backed list: owner-supplied (Vaclav Vislous), verified against the registry (3 tickets = NSTRANA 720).',
  '',
].join('\n')
writeFileSync(OUT, `${header}export const CANDIDATES = {\n${entries.join('\n')}\n}\n\nexport const PIRATE_BACKED = [\n${list.join('\n')}\n]\n`)
console.log(`wrote ${OUT}: ${candidates.length} candidates, ${backed.length} Pirate-backed`)
